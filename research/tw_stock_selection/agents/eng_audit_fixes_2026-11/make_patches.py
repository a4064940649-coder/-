import json, sys
from pathlib import Path
ROOT = Path('/home/user/-'); HERE = Path(__file__).resolve().parent
P = []
_cache = {}


def text(f):
    if f not in _cache:
        _cache[f] = (ROOT / f).read_text(encoding='utf-8')
    return _cache[f]


def line(f, *must, nth=None):
    """回傳檔案裡同時含有 must 各字串的那一整行（必須唯一，除非給 nth）。"""
    hit = [l for l in text(f).split('\n') if all(m in l for m in must)]
    if nth is not None:
        return hit[nth]
    assert len(hit) == 1, (f, must, len(hit))
    return hit[0]


def add(f, old, new, why, cat, cond=None, kind='文件'):
    n = text(f).count(old)
    assert n == 1, f'原文片段在 {f} 出現 {n} 次：{old[:60]}'
    assert old != new
    P.append({'編號': len(P) + 1, '類別': cat, '種類': kind, '檔案': f, '原文片段': old, '建議改成': new, '理由': why, **({'前提': cond} if cond else {})})


